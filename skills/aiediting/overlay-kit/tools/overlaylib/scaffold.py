"""The working folder: deploy the template, keep the generated indexes, duration, logo, helper scripts."""
from __future__ import annotations

import re
import shutil
from pathlib import Path
from typing import List, Optional

from .common import KIT, TEMPLATE, ToolError, say, write_atomic

LOGO_EXT = {".svg", ".png"}
SEG_ID = re.compile(r"^[a-z0-9]+$")


def deploy_template(work: Path) -> bool:
    """Copy the template once. A folder that already has it is left alone: scenes are the person's work."""
    if (work / "src" / "scenes" / "seg-a.tsx").is_file():
        say("Шаблон уже развёрнут, сцены не трогаю.")
        return False
    work.mkdir(parents=True, exist_ok=True)
    shutil.copytree(str(TEMPLATE), str(work), dirs_exist_ok=True)
    return True


def segment_ids(work: Path) -> List[str]:
    ids = []
    for f in sorted((work / "src" / "scenes").glob("seg-*.tsx")):
        ident = f.stem[4:]
        if not SEG_ID.match(ident):
            raise ToolError("Имя сцены {} не подходит: после seg- допустимы строчные латинские буквы и цифры.".format(f.name))
        ids.append(ident)
    return ids


def write_index(work: Path) -> List[str]:
    """src/scenes/index.ts and src/data/all-layouts.ts list every seg-<x>.tsx / layouts-<x>.ts that exists."""
    ids = segment_ids(work)
    if not ids:
        raise ToolError("В src/scenes нет ни одного seg-*.tsx.")
    names = ["s_" + i for i in ids]
    scenes = ["// Generated by tools/overlay.py (index). Do not edit: it lists every src/scenes/seg-<x>.tsx.",
              'import { Cue } from "../kit/Sound";']
    scenes += ['import * as {} from "./seg-{}";'.format(n, i) for n, i in zip(names, ids)]
    scenes += ['import { Scene } from "./types";', "", "const parts = [{}];".format(", ".join(names)), "",
               "export const SCENES: Scene[] = parts.flatMap((p) => p.scenes);",
               "export const ALL_CUES: Cue[] = parts.flatMap((p) => p.cues);", ""]
    write_atomic(work / "src" / "scenes" / "index.ts", "\n".join(scenes))
    layouts = ["// Generated by tools/overlay.py (index). Do not edit: it lists every src/data/layouts-<x>.ts.",
               'import { LayoutKey } from "./layout-types";']
    have = [i for i in ids if (work / "src" / "data" / "layouts-{}.ts".format(i)).is_file()]
    layouts += ['import {{ LAYOUTS_{} }} from "./layouts-{}";'.format(i.upper(), i) for i in have]
    layouts += ["", "export const ALL_LAYOUTS: readonly LayoutKey[] = [{}];".format(", ".join("...LAYOUTS_" + i.upper() for i in have)), ""]
    write_atomic(work / "src" / "data" / "all-layouts.ts", "\n".join(layouts))
    return ids


def set_duration(work: Path, seconds: float) -> None:
    path = work / "src" / "data" / "layouts.ts"
    text = path.read_text(encoding="utf-8")
    new, n = re.subn(r"DURATION = [\d.]+", "DURATION = {:.2f}".format(seconds), text, count=1)
    if n != 1:
        raise ToolError("В src/data/layouts.ts нет строки DURATION = ... Шаблон изменён?")
    write_atomic(path, new)


def add_logo(work: Path, logo: Optional[str]) -> Optional[str]:
    """Copy --logo to public/logos/logo.<ext>; returns the path design.json should carry (or None)."""
    folder = work / "public" / "logos"
    if logo:
        src = Path(logo).expanduser()
        if not src.is_file() or src.suffix.lower() not in LOGO_EXT:
            raise ToolError("--logo: нужен файл SVG или PNG, а передано: {}".format(logo))
        folder.mkdir(parents=True, exist_ok=True)
        for old in folder.glob("logo.*"):
            old.unlink()
        shutil.copyfile(str(src), str(folder / ("logo" + src.suffix.lower())))
    found = next(iter(sorted(folder.glob("logo.*"))), None) if folder.is_dir() else None
    return "logos/" + found.name if found else None


def install_helpers(work: Path) -> None:
    """Node helpers must sit inside the folder to see its node_modules (playwright)."""
    dst = work / "tools-local"
    dst.mkdir(exist_ok=True)
    for name in sorted((KIT / "tools").glob("*.mjs")) + sorted((KIT / "tools").glob("capture-*.js")):
        shutil.copyfile(str(name), str(dst / name.name))
    for sub in ("public/screens", "public/frames", "raw", "raw/snapshots", "out"):
        (work / sub).mkdir(parents=True, exist_ok=True)


def use_example(work: Path, force: bool) -> None:
    """Put examples/ scenes in as segment A (the neutral sample) with its demo screen."""
    ex = KIT / "examples"
    target = work / "src" / "scenes" / "seg-a.tsx"
    if target.is_file() and "scenes: Scene[] = []" not in target.read_text(encoding="utf-8") and not force:
        raise ToolError("Сцены сегмента A уже заполнены. Чтобы заменить их образцом, добавьте --force.")
    shutil.copyfile(str(ex / "seg-a.tsx"), str(target))
    shutil.copyfile(str(ex / "layouts-a.ts"), str(work / "src" / "data" / "layouts-a.ts"))
    (work / "public" / "screens").mkdir(parents=True, exist_ok=True)
    for png in sorted((ex / "screens").glob("*.png")):
        shutil.copyfile(str(png), str(work / "public" / "screens" / png.name))
