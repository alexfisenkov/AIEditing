"""`vertical-init`: put the vertical set (template/src/vertical) into a working folder, new or one of a long video.

The files of the set can be renewed. The data (spans.json) and the scenes (c<N>.tsx) are the person's work: they are written only
when missing, and the scenes never.
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path
from typing import Dict, List

from . import vmap, vspans
from .media import duration_of
from .common import KIT, TEMPLATE, ToolError, say, warn, work_dir, write_atomic

SET_FILES = ["VKit.tsx", "VPresenter.tsx", "VRoot.tsx", "audit.tsx", "clips.ts", "geometry.ts", "safe.ts", "index.ts"]
SCENE = re.compile(r"^c(\d+)\.tsx$")
HELPER = "vertical-frames.mjs"
USE_T = re.compile(r"export const useT = \(\) => toOld\(useCurrentFrame\(\) ?/ ?FPS\);")
FRAME_MAP = """// A vertical clip lays its own map over this: frame of the clip -> second of the source file (vertical/VRoot.tsx).
// The long video never sets one, so for it nothing changes.
let frameToNew: (frame: number) => number = (f) => f / FPS;
export const setFrameMap = (map: (frame: number) => number) => {
  frameToNew = map;
};

export const useT = () => toOld(frameToNew(useCurrentFrame()));"""
MARK_LINE = """
// The frame that marks a place on a screenshot: "overlay.mark" in the design's tokens.json, a neutral ring when there is none
export const MARK: string = (design as { MARK?: string }).MARK ?? "0 0 0 2.5px #FFFFFF, 0 0 0 4px rgba(14,14,16,.7)";
"""


def scene_ids(vertical: Path) -> List[str]:
    found = [m for m in (SCENE.match(p.name) for p in vertical.glob("c*.tsx")) if m]
    return ["c" + n for n in sorted((m.group(1) for m in found), key=int)]


def write_clips_index(work: Path) -> List[str]:
    """src/vertical/index-clips.ts lists every c<N>.tsx that exists."""
    vertical = work / "src" / "vertical"
    ids = scene_ids(vertical)
    lines = ["// Generated by tools/overlay.py (vertical-init, vertical-check, vertical-final). Do not edit: it lists every src/vertical/c<N>.tsx.",
             'import React from "react";', 'import { VKey } from "./VPresenter";']
    lines += ['import {{ {0} }} from "./{0}";'.format(i) for i in ids]
    lines += ["", "export type ClipPlan = { keys: readonly VKey[]; scenes: readonly { from: number; to: number; C: React.FC }[] };", "",
              "export const CLIPS: Record<string, ClipPlan> = {{ {} }};".format(", ".join(ids)), ""]
    write_atomic(vertical / "index-clips.ts", "\n".join(lines))
    return ids


def patch_kit(work: Path) -> List[str]:
    """A folder made before the vertical set lacks setFrameMap in kit/time.ts and MARK in kit/tokens.ts: add them, change nothing else."""
    done = []
    time_ts = work / "src" / "kit" / "time.ts"
    text = time_ts.read_text(encoding="utf-8") if time_ts.is_file() else ""
    if "setFrameMap" not in text:
        if not USE_T.search(text):
            raise ToolError("src/kit/time.ts не такой, как в шаблоне: нет строки «export const useT = () => toOld(useCurrentFrame() / FPS);». "
                            "Добавьте setFrameMap по образцу template/src/kit/time.ts и повторите.")
        write_atomic(time_ts, USE_T.sub(lambda _: FRAME_MAP, text, count=1))
        done.append("src/kit/time.ts: добавлен setFrameMap")
    tokens_ts = work / "src" / "kit" / "tokens.ts"
    text = tokens_ts.read_text(encoding="utf-8") if tokens_ts.is_file() else ""
    if "export const MARK" not in text:
        if 'import design from "../data/design.json"' not in text:
            raise ToolError("src/kit/tokens.ts не читает data/design.json, как шаблон: добавьте MARK по образцу template/src/kit/tokens.ts и повторите.")
        write_atomic(tokens_ts, text.rstrip("\n") + "\n" + MARK_LINE)
        done.append("src/kit/tokens.ts: добавлен MARK")
    return done


def install_helper(work: Path) -> None:
    dst = work / "tools-local"
    dst.mkdir(exist_ok=True)
    shutil.copyfile(str(KIT / "tools" / HELPER), str(dst / HELPER))


def verify_source(work: Path, data: Dict) -> None:
    if data.get("source_seconds") is not None:
        vspans.check_source_seconds(data, duration_of(work / "public" / "clips" / "source.mp4"))


def run_init(args) -> int:
    work = work_dir(args.work)
    for need in ("public/clips/source.mp4", "src/data/face.json"):
        if not (work / need).is_file():
            raise ToolError("В {} нет {}: сначала overlay.py prepare <видео 16:9> <папка> ...".format(work, need))
    given = vspans.load(Path(args.spans)) if args.spans else None
    if given is not None:
        verify_source(work, given)  # a file written for another recording stops here, before anything is written
    vertical = work / "src" / "vertical"
    spans_file = vertical / "spans.json"
    same = given is not None and spans_file.is_file() and Path(args.spans).expanduser().resolve() == spans_file.resolve()
    if given is not None and spans_file.is_file() and not same and not args.renew:
        raise ToolError("{} уже есть, и он ваш. Чтобы заменить его файлом {}, добавьте --renew.".format(spans_file, args.spans))
    vertical.mkdir(parents=True, exist_ok=True)
    src = TEMPLATE / "src" / "vertical"
    kept, wrote = [], []
    for name in SET_FILES:
        if (vertical / name).is_file() and not args.renew:
            kept.append(name)
            continue
        shutil.copyfile(str(src / name), str(vertical / name))
        wrote.append(name)
    if same:
        say("--spans указывает на тот же src/vertical/spans.json: заменять нечем, файл оставлен как есть.")
    elif given is not None:
        shutil.copyfile(str(Path(args.spans).expanduser()), str(spans_file))
        wrote.append("spans.json (ваш)")
    elif not spans_file.is_file():
        shutil.copyfile(str(src / "spans.json"), str(spans_file))
        wrote.append("spans.json (образец)")
    data = vspans.load(spans_file)
    verify_source(work, data)
    rows = vmap.load_rows(work)
    sample = False
    if not scene_ids(vertical) and "c1" in data["spans"]:
        shutil.copyfile(str(KIT / "examples" / "vertical" / "c1.tsx"), str(vertical / "c1.tsx"))
        sample = True
    for note in patch_kit(work):
        say("Дополнил " + note)
    install_helper(work)
    (work / "out" / "vertical").mkdir(parents=True, exist_ok=True)
    ids = write_clips_index(work)
    say("Набор лежит в {}".format(vertical))
    say("Записал: {}".format(", ".join(wrote) or "ничего"))
    if kept:
        say("Оставил как есть (--renew обновит): {}".format(", ".join(kept)))
    say("Сцены: {}{}".format(", ".join(ids) or "нет", " (образец c1, замените его своей сценой)" if sample else ""))
    missing = [c for c in vspans.clip_ids(data) if c not in ids]
    if missing:
        warn("в spans.json есть клипы без сцены: {}. Создайте src/vertical/<клип>.tsx по образцу examples/vertical/c1.tsx.".format(", ".join(missing)))
    if rows:
        warn(vmap.explain(rows))
        track = vmap.face_track_seconds(work)
        try:
            have = duration_of(work / "public" / "clips" / "source.mp4") if track is not None else None
        except ToolError:  # the warning is a courtesy: an unreadable file is reported by the commands that need it
            have = None
        if track is not None and have is not None and abs(track - have) <= vmap.FACE_STEP * 2:
            warn("трек лица src/data/face.json ({:.1f} с) по длине равен файлу, а при карте времени сцены читают его в секундах сцены (он длиннее файла). "
                 "Трек от другого файла: возьмите face.json и time-map.json вместе со сценами из папки длинного ролика.".format(track))
    say("Дальше: поправьте spans.json (отрезки, призыв), напишите сцены, затем overlay.py vertical-check <папка>.")
    return 0
